import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ALL_MASK, SHARDS } from '../src/engine.ts'
import { resolveExperimental } from './naming-lab.ts'

export const APPROVED_NAMING_VERSION = 'relationships-v5'
export const APPROVED_NAMES_SHA256 = 'a265a9f6b44e6974bd7aec21e9b7027a3acf14a513e1d1849091b687582e626e'
const target = fileURLToPath(new URL('../src/naming-v5.generated.ts', import.meta.url))

export function generateApprovedNaming(): string {
  const names = Array.from({ length: ALL_MASK + 1 }, (_, mask) =>
    mask ? resolveExperimental(mask, 'relationships-v5').name : '')
  const digest = createHash('sha256').update(JSON.stringify(names)).digest('hex')
  if (digest !== APPROVED_NAMES_SHA256) {
    throw new Error('The computed mapping differs from the user-approved v5 fingerprint. Do not promote changed interpretations without approval.')
  }
  if (names.slice(1).some(name => !/^[A-Za-z]+$/.test(name))) throw new Error('Approved names must be single-word concepts.')
  const vocabulary = ['', ...new Set(names.slice(1).sort())]
  if (vocabulary.length > 256) throw new Error('Approved naming dictionary exceeds its one-byte encoding.')
  const indices = new Map(vocabulary.map((name, index) => [name, index]))
  const encoded = Buffer.from(names.map(name => {
    const index = indices.get(name)
    if (index === undefined) throw new Error(`Missing dictionary index for ${name}.`)
    return index
  })).toString('base64')
  return [
    '// Generated by tools\\generate-approved-naming.ts. Do not edit by hand.',
    `export const V5_NAMING_VERSION = '${APPROVED_NAMING_VERSION}' as const`,
    `export const V5_METADATA = ${JSON.stringify({
      schema: 1, version: APPROVED_NAMING_VERSION, approval: 'user-approved-presented-v5-mapping',
      namesSha256: digest, masks: ALL_MASK, mergedMasks: ALL_MASK - SHARDS.length,
      source: 'Open English Wordnet 2025 and existing project concepts; see NAMING-NOTICES.txt',
      sourceArchiveSha256: '38b16326159f51853626b7d24a44c453fa88ab33f06fce5ec8fc5996d1c2be93',
      shardOrder: SHARDS.map(shard => shard.name),
    }, null, 2)} as const`,
    `export const V5_NAMES: readonly string[] = ${JSON.stringify(vocabulary, null, 2)}`,
    `export const V5_NAME_INDEX_BASE64 = '${encoded}'`,
    '',
  ].join('\n')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2)
  if (args.some(arg => arg !== '--check') || args.length > 1) throw new Error('Usage: generate-approved-naming.ts [--check]')
  const generated = generateApprovedNaming()
  if (args[0] === '--check') {
    if (readFileSync(target, 'utf8') !== generated) throw new Error('The checked-in approved naming lookup is stale.')
    console.log(`Approved ${APPROVED_NAMING_VERSION} lookup matches ${APPROVED_NAMES_SHA256}.`)
  } else {
    writeFileSync(target, generated, 'utf8')
    console.log(`Generated approved ${APPROVED_NAMING_VERSION} lookup: ${APPROVED_NAMES_SHA256}.`)
  }
}
